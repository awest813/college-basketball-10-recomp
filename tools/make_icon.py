"""Draws the port's icon, a plain basketball, and writes it in the two forms the build uses.

    python tools/make_icon.py   (no -I: Pillow is usually a user site package)

src/ncaabb10.ico     Windows: the executable's icon resource (Explorer, the taskbar, the window).
src/window_icon.inc  Linux: 64x64 RGBA pixels the front end gives SDL for the window icon.

Needs Pillow. Both outputs are committed, so a build does not run this.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SIZE = 1024  # Drawn large, then scaled down, for smooth edges at every size.
ORANGE = (226, 110, 32, 255)
SHADE = (176, 74, 18, 255)
SEAM = (34, 18, 10, 255)


def draw() -> Image.Image:
    image = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(image)
    margin = SIZE * 0.04
    box = (margin, margin, SIZE - margin, SIZE - margin)
    d.ellipse(box, fill=SHADE)
    # A lighter disc toward the top left reads as light on the ball.
    inset = SIZE * 0.07
    d.ellipse((margin + inset * 0.3, margin + inset * 0.3, SIZE - margin - inset * 1.4,
               SIZE - margin - inset * 1.4), fill=ORANGE)
    seam = int(SIZE * 0.045)
    c = SIZE / 2
    r = c - margin
    # Vertical and horizontal seams through the middle.
    d.line((c, margin, c, SIZE - margin), fill=SEAM, width=seam)
    d.line((margin, c, SIZE - margin, c), fill=SEAM, width=seam)
    # The two curved side seams: arcs of a larger circle centered outside the ball.
    for side in (-1, 1):
        cx = c + side * r * 1.25
        rr = r * 0.95
        d.arc((cx - rr, c - rr, cx + rr, c + rr), 0, 360, fill=SEAM, width=seam)
    # Clip everything to the ball and add its outline.
    mask = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(mask).ellipse(box, fill=255)
    clipped = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    clipped.paste(image, (0, 0), mask)
    ImageDraw.Draw(clipped).ellipse(box, outline=SEAM, width=seam)
    return clipped


def main() -> None:
    big = draw()
    sizes = [16, 24, 32, 48, 64, 128, 256]
    big.resize((256, 256), Image.LANCZOS).save(ROOT / "src/ncaabb10.ico",
                                               sizes=[(s, s) for s in sizes])
    small = big.resize((64, 64), Image.LANCZOS)
    data = small.tobytes()  # RGBA, row by row.
    rows = []
    for i in range(0, len(data), 32):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",")
    text = ("// Generated by tools/make_icon.py: the 64x64 window icon, RGBA, top row first.\n"
            "static constexpr int kWindowIconSize = 64;\n"
            "static constexpr unsigned char kWindowIcon[] = {\n" + "\n".join(rows) + "\n};\n")
    (ROOT / "src/window_icon.inc").write_text(text, encoding="ascii", newline="\n")
    big.resize((256, 256), Image.LANCZOS).save(ROOT / "out/icon_preview.png")
    print("wrote src/ncaabb10.ico and src/window_icon.inc")


if __name__ == "__main__":
    main()
